// Разговорные слова и обороты приводим к тем, что понимают правки (k_edit, k_more).
// Вызывается для каждой части фразы до разбора: edSyn(c). Относительные размеры ("шире на 20 см") - edRel(c).
const ED_SYN=[
  // глаголы
  [/^(повес[а-я]*|прикрут[а-я]*|впихни|засунь|воткни|вставь|докинь|допиши|вкинь|присобачь|сделай ещ[её]|ещ[её])\s+/,"добавь "],
  [/^(выкинь|выбрось|снеси|убрать|удалить|не надо|не нужн[аоы]?|без)\s+(?=(шкаф|ящик|полк|двер|секци|мойк|раковин|посудомо|духов|пенал|вытяжк|сушк|бутылочн))/,"убери "],
  [/^(поменяй|смени|измени)\s+(?=.*\s+на\s+)/,"замени "],
  // кухня: предметы
  [/раковин/g,"мойк"],[/мойк[а-я]* (?:с )?тумб[а-я]*/g,"мойку"],
  [/холодос[а-я]*|холодильничек/g,"холодильник"],
  [/сушилк|посудосушител[а-я]*|сушилок/g,"сушк"],
  [/посудомоечн[а-я]* машин[а-я]*|посудомойк[а-я]* машин[а-я]*|посудомоечник/g,"посудомойку"],
  [/варочн[а-я]* (панел[а-я]*|поверхност[а-я]*)|варк[ау]|индукци[а-я]*/g,"духовку"],
  [/духов[а-я]* шкаф[а-я]*/g,"духовку"],
  [/микроволнов[а-я]*|микроволнушк[а-я]*|свчшк[а-я]*/g,"свч"],
  [/шкафчик[а-я]*/g,"шкаф"],[/тумбочк[а-я]*/g,"тумбу"],
  [/(шкаф[а-я]*|модул[а-я]*) (сверху|наверху|над кухней|на стене|навесн[а-я]*)/g,"верхний шкаф"],
  [/(шкаф[а-я]*|модул[а-я]*) (снизу|внизу|напольн[а-я]*)/g,"нижний шкаф"],
  [/(^|\s)навесн[а-я]*(?= |$)/g,"$1верхний"],[/(^|\s)напольн[а-я]*(?= |$)/g,"$1нижний"],
  [/колонк[а-я]*|колонн[а-я]*|высок[а-я]* шкаф[а-я]*/g,"пенал"],
  [/выдвижн[а-я]* (ящик[а-я]*)/g,"$1"],[/ящичк[а-я]*/g,"ящик"],
  [/(^|\s)верх(?= \d)/,"$1верхние шкафы"],[/(^|\s)низ(?= \d)/,"$1нижние шкафы"],
  [/^(длина кухни|длина гарнитура|длина|стена|кухня|гарнитур)\s+(?=\d)/,"основная стена "],
  // купе
  [/вешалк[а-я]*|перекладин[а-я]*|штанг[а-я]*/g,"штангу"],
  [/зеркальн[а-я]*/g,"зеркало"],
  // общее
  [/полочк[а-я]*/g,"полку"],[/дверк[а-я]*|дверц[а-я]*|створк[а-я]*/g,"дверь"]
];
function edSyn(c){
  let t=" "+c+" "; t=t.slice(1,-1);
  for(const [rx,to] of ED_SYN) t=t.replace(rx,to);
  // голое "ящик" / "полку" / "дверь" / "штангу" - значит добавить
  if(/^(ящик|полк[ау]|дверь|штангу|секцию|антресоль|подсветку)( |$)/.test(t)) t="добавь "+t;
  if(/^ящики (внизу|снизу)$/.test(t)) t="добавь 2 ящика";
  return t.replace(/\s+/g," ").trim();
}
// относительные размеры: "шире на 20 см", "сделай мойку пошире", "выше на 10", "кухню короче на 30"
function edRel(c){
  const m=c.match(/^(?:сделай |сделать |пусть будет |чуть |немного )*(.*?)\s*(?:чуть |немного |на )?(по)?(шире|уже|выше|ниже|глубже|мельче|длиннее|короче|больше|меньше)(?: на (\d+(?:[.,]\d+)?)\s*(мм|см|м|сантиметр[а-я]*|миллиметр[а-я]*|метр[а-я]*)?)?$/);
  if(!m) return null;
  const obj=(m[1]||"").replace(/^(сделай|сделать)\s+/,"").trim(), w=m[3];
  let d=100; if(m[4]){ const n=parseFloat(m[4].replace(",",".")), u=m[5]||"";
    d = /^мм|миллим/.test(u)?n : /^см|сант/.test(u)?n*10 : /^м/.test(u)?n*1000 : (n<100?n*10:n); }
  const sg=/шире|выше|глубже|длиннее|больше/.test(w)?1:-1, dim=/шире|уже|длиннее|короче|больше|меньше/.test(w)?"w":/выше|ниже/.test(w)?"h":"d";
  d=Math.round(d)*sg;
  if(S.mode==="kupe"){ const K=S.kupe, key=dim==="w"?"W":dim==="h"?"H":"D", nm={W:"Ширина",H:"Высота",D:"Глубина"}[key];
    K[key]=clamp(K[key]+d, key==="D"?300:key==="H"?1000:600, key==="W"?6000:key==="H"?3200:1000); return [`${nm} ${fmt(K[key])} мм`]; }
  if(S.mode==="univ"){ const p=S.u.prms&&S.u.prms[S.u.tpl]; const key=dim==="w"?"W":dim==="h"?"H":"D"; if(!p||p[key]==null) return null;
    p[key]=Math.max(100,+p[key]+d); return [`${({W:"Ширина",H:"Высота",D:"Глубина"})[key]} ${fmt(p[key])} мм`]; }
  const tryEd=x=>{ for(const v of [x, x.replace(/у(?= |$)/,"а").replace(/ю(?= |$)/,"я")]){ try{ let r=edKitchen(v); if(!r||!r.length) r=edProps(v); if(r&&r.length) return r; }catch(e){} } return null; };
  if(S.mode==="kitchen"){ const K=S.kit;
    if(!obj || /^(кухн|гарнитур|стен|основн)/.test(obj)){ if(dim!=="w") return null; return tryEd(`основная стена ${K.walls[0].len+d}`); }
    if(/^верхн/.test(obj)&&dim==="h"){ K.Hu=clamp(K.Hu+d,300,1200); return [`Верхние шкафы ${fmt(K.Hu)} мм`]; }
    if(/^(нижн|столешниц)/.test(obj)&&dim==="h"){ K.Hl=clamp(K.Hl+d,500,950); return [`Нижние шкафы ${fmt(K.Hl)} мм`]; }
    const type=edType(obj); if(!type||dim!=="w") return null;
    for(const wl of K.walls) for(const r of ["lower","upper"]) { const md=wl[r].find(x=>x.t===type); if(md) return tryEd(`${obj} ${md.w+d}`); }
  }
  return null;
}
// верхние шкафы до потолка: "верхние до потолка 2,7" (без числа - просим высоту потолка)
function edCeil(c){
  if(S.mode!=="kitchen"||!/верхн[а-я ]*до потолк|до потолк[а-я ]*верхн/.test(c)) return null;
  const n=(c.match(/(\d+(?:[.,]\d+)?)/)||[])[1]; if(!n) throw new Error('Скажите высоту потолка: "верхние до потолка 2,7"');
  let mm=parseFloat(n.replace(",",".")); mm = mm<10?mm*1000 : mm<400?mm*10 : mm;
  const K=S.kit, top=(MAT(K.top)||{}).t||38, Hu=Math.round(mm-(+K.PL||0)-K.Hl-top-K.apronH-10);
  if(Hu<300) throw new Error("Над столешницей не хватает места для верхних шкафов");
  K.Hu=clamp(Hu,300,1200); return [`Верхние шкафы до потолка: ${fmt(K.Hu)} мм`];
}
// цвет / декор словами, которые не меняют материал: "столешница под дерево", "корпус серый", "фасады цвет графит"
function edNote(c){
  const m=c.match(/^(столешниц[а-я]*|фасад[а-я]*|корпус[а-я]*|ручк[а-я]*|фартук[а-я]*|профил[а-я]*)\s+(?:цвет[а-я]*\s+|под\s+|в цвет[а-я]*\s+)?([а-я][а-я -]{2,})$/);
  if(!m) return null; const note=c.trim();
  S.decor=[S.decor,note].filter(Boolean).join(", "); return [`Записал в "Цвет и декор": ${note}`];
}
// кухня: слова из описания в виде правки ("встроенный холодильник", "духовка в пенале", "посудомойка 45" - если её ещё нет)
function edKitWords(c){
  if(S.mode!=="kitchen") return null; const K=S.kit, has=t=>K.walls.some(w=>w.lower.some(m=>m.t===t));
  if(/^(встроенн[а-я]* холодильник[а-я]*|холодильник[а-я]* встроенн[а-я]*|холодильник в пенал[а-я]*)$/.test(c))
    return edKitchen(has("l_gap")?"замени холодильник на встроенный холодильник":"добавь встроенный холодильник");
  if(/^(холодильник[а-я]* (отдельно|отдельностоящ[а-я]*|свой|не встроенн[а-я]*)|отдельн[а-я]* холодильник[а-я]*)$/.test(c))
    return edKitchen(has("t_fridge")?"замени встроенный холодильник на холодильник":"добавь холодильник");
  if(/^(духов[а-я]* (в|на) пенал[а-я]*|пенал[а-я]* (под|для|с) духов[а-я]*)$/.test(c))
    return edKitchen(has("l_oven")?"замени духовку на пенал духовка":"добавь пенал духовка");
  return null;
}
// "посудомойка 45", когда её нет - добавить
function edAddMissing(c, err){
  if(S.mode!=="kitchen"||!/Не нашёл модуль/.test(err||"")) return null;
  const m=c.match(/^([а-я][а-я ]*?) (\d{2,4})( мм)?$/); if(!m||/^(добав|убер|замен|перенес)/.test(m[1])) return null;
  const r=edKitchen("добавь "+c); return r&&r.length?r:null;
}
